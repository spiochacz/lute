import { readFileSync } from "node:fs";
import { CONFIGS, engines } from "../corpus.ts";
import { editor } from "../../../src/index.ts";
import { WYSIWYG_ADAPTER } from "../../../src/incremental/sandbox.ts";
import { vditorDOM2MdPreprocess } from "../../../src/vditor_wysiwyg.ts";
import { Cache, compose } from "./fast.ts";
const h = vditorDOM2MdPreprocess(readFileSync(`${process.env.FIX}/spec.wysiwyg.html`, "utf8").split(editor.Zwsp).join(""));
const { port } = engines(CONFIGS[0], "wysiwyg");
const ref = port.vditorDOM2Md(h);
const o = compose(port, WYSIWYG_ADAPTER, new Cache(), h)!;
console.log(ref.length, o.length);
let i = 0; while (i < ref.length && ref[i] === o[i]) i++;
console.log("first diff at", i, JSON.stringify(ref.slice(i - 80, i + 60)), "\n---\n", JSON.stringify(o.slice(i - 80, i + 60)));
