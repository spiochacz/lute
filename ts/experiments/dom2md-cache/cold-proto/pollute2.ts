import { readFileSync } from "node:fs";
import { performance } from "node:perf_hooks";
import { CONFIGS, engines } from "../corpus.ts";
import { editor } from "../../../src/index.ts";
import { State } from "../../../src/incremental/cache.ts";
import { tryDom2Md } from "./assemble_timed.ts";
import { SW, WYSIWYG_ADAPTER, IR_ADAPTER } from "./sandbox_timed.ts";
const FIX = process.env.FIX!;
const mode = (process.argv[2] ?? "wysiwyg") as "wysiwyg" | "ir";
const v = process.argv[3] ?? "baseline";
const sw: any = { baseline: {}, noDomGuard: { noDomGuard: true }, noAst: { noAstGuard: true, noLastOut: true }, none: { noDomGuard: true, noAstGuard: true, noLastOut: true }, astOnly: { noLastOut: true, noDomGuard: true }, lastOutOnly: { noAstGuard: true, noDomGuard: true }, domOnly: { noAstGuard: true, noLastOut: true } }[v];
Object.assign(SW, sw);
const h = readFileSync(`${FIX}/spec.${mode}.html`, "utf8").split(editor.Zwsp).join("");
const { port } = engines(CONFIGS[0], mode);
const call = (s: string) => (mode === "wysiwyg" ? port.VditorDOM2Md(s) : port.VditorIRDOM2Md(s));
const bestN = () => { let b = Infinity; for (let i = 0; i < 15; i++) { const t = performance.now(); call(h); b = Math.min(b, performance.now() - t); } return b; };
const before = bestN();
const ad = mode === "wysiwyg" ? WYSIWYG_ADAPTER : IR_ADAPTER;
let cold = Infinity;
for (let i = 0; i < 10; i++) { const t = performance.now(); tryDom2Md(new State({}), port, ad, h); cold = Math.min(cold, performance.now() - t); }
const after = bestN();
console.log(mode, v.padEnd(10), "normal before", before.toFixed(1), "cold sandbox", cold.toFixed(1), "normal after", after.toFixed(1));
