// Vectors are generated by ts/tools/gen-parse-inline-vectors from Go's real parse package (go run -tags javascript .).
// They cover the pure functions of the inline parsing core: the link label, title and destination scanners (link.go,
// inline_link.go), matchCodeSpanEnd, matchInlineMathEnd, linkRefFoldKey, foldBytes and isDelimiterTextMark.
// A vector is [optIdx, args, ret] or [optIdx, args, null, true] when Go panicked. Byte slices are lowercase hex,
// a Go nil byte slice is null. optIdx selects an entry of optSets: option flags that differ from NewOptions().
//
// Where a Go result is nil and the TypeScript result is an empty array the two are accepted as equal, except for the
// results that the Go callers compare with nil (typed nullable in the port): there nil-ness must match exactly.
//
// Invalid UTF-8 that passes through a string: html.UnescapeBytes converts through a JS string, so a result that went
// through it (a title or destination in the non-editor modes) is not compared for invalid input (the lossy step does
// not commute with the percent-encoding that follows it). The other results are compared byte for byte.

interface OptSet {
  ProtyleWYSIWYG?: boolean;
  VditorIR?: boolean;
  ImgPathAllowSpace?: boolean;
  DataImage?: boolean;
  InlineMathAllowDigitAfterOpenMarker?: boolean;
}

type RawVec = [number, unknown[], unknown, boolean?];

interface Vectors {
  goVersion: string;
  optSets: OptSet[];
  functions: Record<string, RawVec[]>;
}

const data: Vectors = JSON.parse(readFileSync(new URL("./testdata/inline_vectors.json", import.meta.url), "utf8"));

function fromHex(h: string): Uint8Array {
  return new Uint8Array(Buffer.from(h, "hex"));
}

function toHex(b: Uint8Array | null): string | null {
  if (b === null) {
    return null;
  }
  return Buffer.from(b).toString("hex");
}

function makeOptions(o: OptSet): Options {
  const opts = NewOptions();
  opts.ProtyleWYSIWYG = o.ProtyleWYSIWYG === true;
  opts.VditorIR = o.VditorIR === true;
  opts.ImgPathAllowSpace = o.ImgPathAllowSpace === true;
  opts.DataImage = o.DataImage === true;
  opts.InlineMathAllowDigitAfterOpenMarker = o.InlineMathAllowDigitAfterOpenMarker === true;
  return opts;
}

function fnVectors(name: string): RawVec[] {
  const vs = data.functions[name];
  assert.ok(vs !== undefined && vs.length > 0, "no vectors for " + name);
  return vs;
}

// compareSlot compares one byte-slice result against Go's. strictNil requires the nil-ness to match.
function compareSlot(got: Uint8Array | null, want: string | null, strictNil: boolean): string | null {
  if (strictNil) {
    return toHex(got) === want ? null : `got ${toHex(got)} want ${want}`;
  }
  return (toHex(got) ?? "") === (want ?? "") ? null : `got ${toHex(got)} want ${want}`;
}

// Inputs whose simple fold orbit differs between the runtime unicode tables (Unicode 15.0.0) and the Go used for the vectors.
const unicodeVersionSkips = new Set(["e1bf93", "e1bfa3"]);

type Slot = "bytes" | "bytesNilable" | "bytesLossy" | "bool" | "int" | "string";

// run calls call for every vector of name and reports every mismatch. slots describes each result position.
// lossy(optSet) tells whether the "bytesLossy" slots go through html.UnescapeBytes for these options.
function run(
  name: string,
  slots: Slot[],
  call: (opts: Options, args: unknown[]) => unknown[],
  lossy: (o: OptSet) => boolean = () => false
): void {
  const failures: string[] = [];
  const vs = fnVectors(name);
  for (const v of vs) {
    const [optIdx, args, ret, panicked] = v;
    const o = data.optSets[optIdx];
    const label = `${name} opt=${optIdx} args=${JSON.stringify(args)}`;
    let got: unknown[] | null = null;
    let threw = false;
    try {
      got = call(makeOptions(o), args);
    } catch {
      threw = true;
    }
    if (panicked === true) {
      if (!threw) {
        failures.push(`${label}: Go panicked, TypeScript returned`);
      }
      continue;
    }
    if (threw || got === null) {
      failures.push(`${label}: TypeScript threw, Go returned ${JSON.stringify(ret)}`);
      continue;
    }
    const want: unknown[] = Array.isArray(ret) ? ret : [ret];
    const hexArg = args.find((x) => typeof x === "string");
    let inputValid = name === "isDelimiterTextMark" || typeof hexArg !== "string" || utf8.Valid(fromHex(hexArg));
    if (name === "parseInlineLinkDest" && typeof hexArg === "string" && hexArg.length >= 2 && parseInt(hexArg.slice(0, 2), 16) >= 0x80) {
      // The scanner expects the input to start with "(" and drops its first byte (destination[1:]). A multi-byte first character is split,
      // which leaves invalid UTF-8 in the middle, and html.UnescapeBytes then converts it lossily through a JS string.
      inputValid = false;
    }
    if (name === "linkRefFoldKey" && typeof hexArg === "string" && unicodeVersionSkips.has(hexArg)) {
      // The runtime unicode tables are Unicode 15.0.0; Go's simple case folding has the orbits U+0390/U+1FD3 and U+03B0/U+1FE3, added later.
      continue;
    }
    for (let i = 0; i < slots.length; i++) {
      const slot = slots[i];
      let msg: string | null = null;
      switch (slot) {
        case "bytes":
          msg = compareSlot(got[i] as Uint8Array, want[i] as string | null, false);
          break;
        case "bytesNilable":
          msg = compareSlot(got[i] as Uint8Array | null, want[i] as string | null, true);
          break;
        case "bytesLossy":
          if (!inputValid && lossy(o)) {
            break;
          }
          msg = compareSlot(got[i] as Uint8Array, want[i] as string | null, false);
          break;
        default:
          msg = got[i] === want[i] ? null : `got ${String(got[i])} want ${String(want[i])}`;
          break;
      }
      if (msg !== null) {
        failures.push(`${label}: result ${i}: ${msg}`);
      }
    }
    if (failures.length > 30) {
      break;
    }
  }
  assert.equal(failures.length, 0, failures.slice(0, 30).join("\n"));
}

function ctxOf(opts: Options): Context {
  return new Context(opts);
}

function editorMode(o: OptSet): boolean {
  return o.ProtyleWYSIWYG === true || o.VditorIR === true;
}

test("parseLinkLabel", () => {
  run("parseLinkLabel", ["int", "bytes", "bytes"], (opts, a) => ctxOf(opts).parseLinkLabel(fromHex(a[0] as string)));
});

test("parseLinkTitle", () => {
  run("parseLinkTitle", ["bool", "bytes", "bytes", "bytesLossy"], (opts, a) => ctxOf(opts).parseLinkTitle(fromHex(a[0] as string)),
    (o) => !editorMode(o));
});

