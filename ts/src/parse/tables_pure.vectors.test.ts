// Vectors are generated by ts/tools/gen-parse-tables-vectors from Go's real parse package.
// Byte slices are lowercase hex, "" is an empty slice and null is a Go nil slice. A vector is {in, out, panic?}.
//
// Where a Go result is a nil byte slice and the TypeScript result is an empty array, the two are accepted as equal,
// except for the Tokens of table nodes and the results typed as nullable (IALs), which are compared exactly.
//
// The modules that need TagAttr (inline_attribute_list.ts, and table_rich_style.ts, transform.ts through it) are imported dynamically.
// When they cannot be imported yet the tests that need them are skipped.

interface Rec {
  in: unknown[];
  out: unknown;
  panic?: boolean;
}

interface Dump {
  t: number;
  tok: string | null;
  align: number;
  ial: string[][] | null;
  aligns: number[] | null;
  kids: Dump[];
}

interface Vectors {
  emoji: {
    aliasUnicode: [string, string][];
    unicodeAliasLen: number;
    single: [string, string][];
    multi: [string, string[]][];
    isEmoji: Rec[];
    imgTokens: Rec[];
    sitePlaceholder: string;
  };
  ial: Record<string, Rec[]>;
  table: Record<string, Rec[]>;
  refs: Record<string, Rec[]>;
  rich_style: Record<string, Rec[]>;
}

