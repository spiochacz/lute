test("Context.parseFileAnnotationRefID", () => {
  for (const r of vectors.refs["parseFileAnnotationRefID"]) {
    if (r.in[0] === "lt65536") {
      // TestFileAnnotationRefRejectsNestedOpenersWithoutConsumingInput of parse/file_annotation_ref_test.go
      const tokens = new Uint8Array(65536).fill(0x3c);
      const [passed, remains, id] = realContext(false).parseFileAnnotationRefID(tokens);
      assert.deepEqual([passed.length, remains.length, id.length], r.out);
      assert.deepEqual(r.out, [0, 65536, 0]);
      continue;
    }
    const [passed, remains, id] = realContext(false).parseFileAnnotationRefID(hexToBytes(r.in[0] as string));
    assert.deepEqual([hexOrEmpty(passed), hexOrEmpty(remains), hexOrEmpty(id)], nilToEmpty(r.out), JSON.stringify(r.in));
  }
});

