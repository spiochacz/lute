// protectTableCellRichStyles unescapes the entity literals with the standard library's html.UnescapeString (parse/table_rich_style.go:61),
// ported in runtime/stdhtml.ts. It must equal Go's result on every recorded literal (lute's own html.UnescapeString does not: it lacks
// entity names without ';' and the two-code-point entities).
test("runtime/stdhtml UnescapeString equals the standard library's html.UnescapeString on the style literals", () => {
  const diffs: string[] = [];
  for (const r of vectors.rich_style["stdlibUnescapeString"]) {
    if (stdhtml.UnescapeString(r.in[0] as string) !== r.out) {
      diffs.push(r.in[0] as string);
    }
  }
  assert.equal(vectors.rich_style["stdlibUnescapeString"].length, 746);
  assert.deepEqual(diffs, []);
});
