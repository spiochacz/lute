// Returns variants of the document with the caret inserted at several positions: start, end, after the first character,
// in the middle, and after every line break.
export function withCarets(doc: string): string[] {
  const positions = new Set<number>([0, doc.length, Math.min(1, doc.length), Math.floor(doc.length / 2)]);
  let nl = doc.indexOf("\n");
  let count = 0;
  while (nl !== -1 && count < 4) {
    positions.add(nl);
    positions.add(nl + 1);
    nl = doc.indexOf("\n", nl + 1);
    count++;
  }
  const ret: string[] = [];
  const adjusted = new Set<number>();
  for (let p of positions) {
    const prev = p > 0 ? doc.charCodeAt(p - 1) : 0;
    const next = p < doc.length ? doc.charCodeAt(p) : 0;
    if (prev >= 0xd800 && prev <= 0xdbff && next >= 0xdc00 && next <= 0xdfff) {
      p++; // do not split a surrogate pair
    }
    adjusted.add(p);
  }
  for (const p of [...adjusted].sort((a, b) => a - b)) {
    ret.push(doc.slice(0, p) + CARET + doc.slice(p));
  }
  return ret;
}

