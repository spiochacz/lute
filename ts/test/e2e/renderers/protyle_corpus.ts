function withCarets(s: string): string[] {
  const out = [s, C + s, s + C];
  const mid = Math.floor(s.length / 2);
  out.push(s.slice(0, mid) + C + s.slice(mid));
  const sp = s.indexOf(" ");
  if (sp > 0) {
    out.push(s.slice(0, sp) + C + s.slice(sp));
  }
  return out;
}

