export const CORPUS: string[] = [];
for (const s of INLINE) {
  for (const v of withCarets(s)) {
    CORPUS.push(v);
  }
}
for (const s of BLOCKS) {
  CORPUS.push(s);
}
// Inline fragments in other containers.
const SOME_INLINE = INLINE.filter((_, i) => i % 3 === 0);
for (const s of SOME_INLINE) {
  CORPUS.push("# " + s);
  CORPUS.push("- " + s);
  CORPUS.push("> " + s);
  CORPUS.push("| " + s.replace(/\|/g, "\\|") + " |\n|---|\n| " + s.replace(/\|/g, "\\|") + " |");
  CORPUS.push("1. [ ] " + s);
}

