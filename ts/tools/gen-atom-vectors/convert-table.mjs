// One-off converter: html/atom/table.go -> ts/src/html/atom/table.ts.
//
// It copies the atom constants, hash0, maxAtomLen, the hash table entries and
// the atomText literal pieces mechanically, in the same order, so no value is
// retyped by hand. It also writes names_gen.go, a list of every atom constant
// that the Go generator references by name (a missing or misspelled constant
// fails to compile there).
//
// Usage (from ts/): node tools/gen-atom-vectors/convert-table.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const goPath = join(here, "../../../html/atom/table.go");
const tsPath = join(here, "../../src/html/atom/table.ts");
const namesPath = join(here, "names_gen.go");

const src = readFileSync(goPath, "utf8").split(/\r?\n/);
const pin = readFileSync(join(here, "../../UPSTREAM_PIN"), "utf8").trim().slice(0, 8);

const license = `// Copyright 2012 The Go Authors. All rights reserved.
// Use of this source code is governed by a BSD-style
// license that can be found in the LICENSE file.`;

const consts = [];
const tableEntries = new Map(); // index -> { value, comment }
let hash0 = null;
let maxAtomLen = null;
let tableLen = null;

let section = "";
for (const line of src) {
  let m;
  if (line === "const (") { section = "consts"; continue; }
  if (line.startsWith("var table")) {
    section = "table";
    m = /\[1 << (\d+)\]Atom/.exec(line);
    if (!m) throw new Error("table length not found: " + line);
    tableLen = 1 << Number(m[1]);
    continue;
  }
  if (section === "consts") {
    if (line === ")") { section = ""; continue; }
    m = /^\t(\w+)\s+Atom = (0x[0-9a-f]+)$/.exec(line);
    if (m) consts.push({ name: m[1], value: m[2] });
    continue;
  }
  if (line.startsWith("const hash0 = ")) {
    hash0 = /= (0x[0-9a-f]+)$/.exec(line)[1];
    continue;
  }
  if (line.startsWith("const maxAtomLen = ")) {
    maxAtomLen = /= (\d+)$/.exec(line)[1];
    continue;
  }
  if (section === "table") {
    if (line === "}") { section = ""; continue; }
    m = /^\t(0x[0-9a-f]+):\s+(0x[0-9a-f]+),\s+\/\/ (.*)$/.exec(line);
    if (m) {
      const idx = Number(m[1]);
      if (tableEntries.has(idx)) throw new Error("duplicate table index " + m[1]);
      tableEntries.set(idx, { value: m[2], comment: m[3] });
    }
  }
}

// The atomText block: first line "const atomText = "...." +", continuation
// lines "\t"...." +", the last one without "+".
const textStart = src.findIndex((l) => l.startsWith("const atomText = "));
if (textStart < 0) throw new Error("atomText not found");
const pieces = [];
for (let i = textStart; i < src.length; i++) {
  const body = i === textStart ? src[i].replace(/^const atomText = /, "") : src[i].replace(/^\t/, "");
  const m = /^"([^"\\]*)"( \+)?$/.exec(body);
  if (!m) throw new Error("unexpected atomText line: " + src[i]);
  pieces.push(m[1]);
  if (!m[2]) break;
}

if (consts.length !== 368) throw new Error("expected 368 constants, got " + consts.length);
if (hash0 === null || maxAtomLen === null || tableLen !== 512) throw new Error("missing header constants");
if (tableEntries.size === 0) throw new Error("no table entries");

const atomText = pieces.join("");

const out = [];
out.push(`// Ported from html/atom/table.go @ ${pin}`);
out.push("");
out.push(license);
out.push("");
out.push("// Generated mechanically from html/atom/table.go by");
out.push("// ts/tools/gen-atom-vectors/convert-table.mjs. The values, their order and");
out.push("// the table layout are the Go ones; do not edit this file by hand.");
out.push("");
out.push("// Atom constants, in the order of table.go.");
for (const c of consts) out.push(`export const ${c.name} = ${c.value};`);
out.push("");
out.push("export const hash0 = " + hash0 + ";");
out.push("");
out.push("export const maxAtomLen = " + maxAtomLen + ";");
out.push("");
out.push("// Perfect hash table, indexed by the FNV hash (512 slots). Empty slots are 0.");
out.push("export const table = new Uint32Array([");
for (let i = 0; i < tableLen; i++) {
  const e = tableEntries.get(i);
  if (e) out.push(`  ${e.value}, // ${i.toString(16)}: ${e.comment}`);
  else out.push(`  0, // ${i.toString(16)}`);
}
out.push("]);");
out.push("");
out.push("// Concatenated atom names. Every name is ASCII, so byte offsets equal UTF-16 offsets.");
out.push("export const atomText =");
pieces.forEach((p, i) => {
  const last = i === pieces.length - 1;
  out.push(`  "${p}"${last ? ";" : " +"}`);
});
out.push("");

writeFileSync(tsPath, out.join("\n"));

// names_gen.go: compile-time references to every constant of the real package.
const g = [];
g.push("// Code generated by convert-table.mjs from html/atom/table.go; DO NOT EDIT.");
g.push("");
g.push("package main");
g.push("");
g.push('import "github.com/88250/lute/html/atom"');
g.push("");
g.push("// goConstRefs lists every atom constant in table.go order, referenced through the");
g.push("// real package so that a missing constant fails to compile.");
g.push("var goConstRefs = []struct {");
g.push("\tname  string");
g.push("\tvalue atom.Atom");
g.push("}{");
for (const c of consts) g.push(`\t{"${c.name}", atom.${c.name}},`);
g.push("}");
g.push("");
writeFileSync(namesPath, g.join("\n"));

console.log(`constants=${consts.length} tableEntries=${tableEntries.size} tableLen=${tableLen} atomTextLen=${atomText.length} hash0=${hash0} maxAtomLen=${maxAtomLen} textPieces=${pieces.length}`);
