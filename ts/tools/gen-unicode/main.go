// Command gen-unicode generates the Unicode tables used by the TypeScript
// runtime (ts/src/runtime/unicode_tables.ts) and the exhaustive checksums
// used by ts/src/runtime/unicode.test.ts.
//
// Every table is computed by calling the real Go functions for every rune in
// 0..0x10FFFF, then merging the results into ranges. Nothing is hand-copied.
//
// Run from this directory:
//
//	go run . -tables ../../src/runtime/unicode_tables.ts -checksums ../../src/runtime/testdata/unicode_checksums.json
package main

import (
	"bufio"
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"runtime"
	"strings"
	"unicode"

	"golang.org/x/text/width"
)

const maxRune = 0x10FFFF

// predicates are the Go predicates exposed as TS functions. The index of each
// entry is its bit in the asciiFlags table.
var predicates = []struct {
	name string
	fn   func(rune) bool
}{
	{"IsLetter", unicode.IsLetter},
	{"IsDigit", unicode.IsDigit},
	{"IsNumber", unicode.IsNumber},
	{"IsPunct", unicode.IsPunct},
	{"IsSymbol", unicode.IsSymbol},
	{"IsSpace", unicode.IsSpace},
	{"IsControl", unicode.IsControl},
	{"IsPrint", unicode.IsPrint},
	{"IsGraphic", unicode.IsGraphic},
	{"IsUpper", unicode.IsUpper},
	{"IsLower", unicode.IsLower},
	{"IsMark", unicode.IsMark},
	{"IsEastAsianWideOrFullwidth", isEastAsianWideOrFullwidth},
}

// tables are Go range tables exposed as TS range tables (used with Is).
var tables = []struct {
	name string
	tab  *unicode.RangeTable
}{
	{"Han", unicode.Han},
	{"Hiragana", unicode.Hiragana},
	{"Katakana", unicode.Katakana},
	{"Hangul", unicode.Hangul},
	{"Zs", unicode.Zs},
	{"Lm", unicode.Lm},
	{"Latin", unicode.Latin},
	{"L", unicode.L},
	{"M", unicode.M},
	{"N", unicode.N},
	{"P", unicode.P},
	{"S", unicode.S},
	{"Nd", unicode.Nd},
	{"Lu", unicode.Lu},
	{"Ll", unicode.Ll},
	{"White_Space", unicode.White_Space},
}

func isEastAsianWideOrFullwidth(r rune) bool {
	kind := width.LookupRune(r).Kind()
	return kind == width.EastAsianWide || kind == width.EastAsianFullwidth
}

// rangeName maps a predicate name to its internal range table name, e.g.
// IsLetter -> LetterRanges.
func rangeName(pred string) string {
	return strings.TrimPrefix(pred, "Is") + "Ranges"
}

// fnvAdd feeds the 4 little-endian bytes of v into a 32-bit FNV-1a hash.
func fnvAdd(h uint32, v uint32) uint32 {
	for i := 0; i < 4; i++ {
		h ^= uint32(byte(v >> (8 * i)))
		h *= 16777619
	}
	return h
}

const fnvOffset = 2166136261

// collect returns the sorted runes in 0..maxRune for which pred is true.
func collect(pred func(rune) bool) []rune {
	var out []rune
	for r := 0; r <= maxRune; r++ {
		if pred(rune(r)) {
			out = append(out, rune(r))
		}
	}
	return out
}

// merge converts sorted runes into inclusive [lo, hi] pairs.
func merge(runes []rune) []rune {
	var out []rune
	for i := 0; i < len(runes); {
		lo := runes[i]
		hi := lo
		j := i + 1
		for j < len(runes) && runes[j] == hi+1 {
			hi = runes[j]
			j++
		}
		out = append(out, lo, hi)
		i = j
	}
	return out
}

func writeNumbers(w *bufio.Writer, name string, values []uint32, perLine int) {
	fmt.Fprintf(w, "export const %s: Uint32Array = new Uint32Array([\n", name)
	for i := 0; i < len(values); i += perLine {
		w.WriteString("  ")
		for j := i; j < i+perLine && j < len(values); j++ {
			fmt.Fprintf(w, "0x%X,", values[j])
			if j+1 < i+perLine && j+1 < len(values) {
				w.WriteString(" ")
			}
		}
		w.WriteString("\n")
	}
	w.WriteString("]);\n\n")
}

func toU32(runes []rune) []uint32 {
	out := make([]uint32, len(runes))
	for i, r := range runes {
		out[i] = uint32(r)
	}
	return out
}

// writeMap writes sorted [rune, mapped] pairs for every rune where f(r) != r.
func writeMap(w *bufio.Writer, name string, f func(rune) rune) int {
	var pairs []uint32
	changed := 0
	for r := 0; r <= maxRune; r++ {
		m := f(rune(r))
		if m != rune(r) {
			changed++
			pairs = append(pairs, uint32(r), uint32(m))
		}
	}
	writeNumbers(w, name, pairs, 8)
	return changed
}

func main() {
	tablesPath := flag.String("tables", "../../src/runtime/unicode_tables.ts", "output TypeScript file")
	checksumsPath := flag.String("checksums", "../../src/runtime/testdata/unicode_checksums.json", "output JSON checksum file")
	flag.Parse()

	goVersion := runtime.Version()
	uver := unicode.Version

	// ---- TypeScript tables -------------------------------------------------
	f, err := os.Create(*tablesPath)
	if err != nil {
		log.Fatal(err)
	}
	w := bufio.NewWriterSize(f, 1<<16)

	fmt.Fprintf(w, "// Code generated by ts/tools/gen-unicode; DO NOT EDIT.\n")
	fmt.Fprintf(w, "//\n")
	fmt.Fprintf(w, "// Generated by %s from unicode.Version %s and golang.org/x/text v0.21.0 (width).\n", goVersion, uver)
	fmt.Fprintf(w, "// Regenerate with the command in ts/tools/gen-unicode/README.md.\n")
	fmt.Fprintf(w, "//\n")
	fmt.Fprintf(w, "// Range tables are flat inclusive [lo, hi] pairs sorted by lo.\n")
	fmt.Fprintf(w, "// Map tables are flat [rune, mapped] pairs sorted by rune.\n")
	fmt.Fprintf(w, "// asciiFlags bit positions (bit i = predicate i):\n")
	for i, p := range predicates {
		fmt.Fprintf(w, "//   bit %d: %s\n", i, p.name)
	}
	fmt.Fprintf(w, "\n")

	// Predicate range tables.
	for _, p := range predicates {
		writeNumbers(w, rangeName(p.name), toU32(merge(collect(p.fn))), 8)
	}

	// Named tables for Is.
	for _, t := range tables {
		tab := t.tab
		writeNumbers(w, t.name, toU32(merge(collect(func(r rune) bool { return unicode.Is(tab, r) }))), 8)
	}

	// ASCII flags: one bit per predicate, computed from the Go predicates.
	fmt.Fprintf(w, "export const asciiFlags: Uint16Array = new Uint16Array([\n")
	for c := 0; c < 128; c++ {
		var flags uint16
		for i, p := range predicates {
			if p.fn(rune(c)) {
				flags |= 1 << i
			}
		}
		if c%8 == 0 {
			w.WriteString("  ")
		}
		fmt.Fprintf(w, "0x%04X,", flags)
		if c%8 == 7 {
			w.WriteString("\n")
		} else {
			w.WriteString(" ")
		}
	}
	fmt.Fprintf(w, "]);\n\n")

	// Case mappings (pairs where the mapping differs from identity).
	upperChanged := writeMap(w, "UpperMap", unicode.ToUpper)
	lowerChanged := writeMap(w, "LowerMap", unicode.ToLower)
	titleChanged := writeMap(w, "TitleMap", unicode.ToTitle)
	foldChanged := writeMap(w, "SimpleFoldMap", unicode.SimpleFold)

	// ASCII fast path for SimpleFold (the orbit of ASCII runes can leave ASCII).
	ascii := make([]uint32, 128)
	for c := 0; c < 128; c++ {
		ascii[c] = uint32(unicode.SimpleFold(rune(c)))
	}
	writeNumbers(w, "asciiSimpleFold", ascii, 8)

	if err := w.Flush(); err != nil {
		log.Fatal(err)
	}
	if err := f.Close(); err != nil {
		log.Fatal(err)
	}

	// ---- Checksums ---------------------------------------------------------
	type entry struct {
		Count    int    `json:"count"`
		Checksum uint32 `json:"checksum"`
	}
	type mapEntry struct {
		Changed  int    `json:"changed"`
		Checksum uint32 `json:"checksum"`
	}
	type probe struct {
		R          int64            `json:"r"`
		Predicates map[string]bool  `json:"predicates"`
		Mappings   map[string]int64 `json:"mappings"`
	}
	out := struct {
		GoVersion      string              `json:"goVersion"`
		UnicodeVersion string              `json:"unicodeVersion"`
		Predicates     map[string]entry    `json:"predicates"`
		Tables         map[string]entry    `json:"tables"`
		Mappings       map[string]mapEntry `json:"mappings"`
		Probes         []probe             `json:"probes"`
	}{
		GoVersion:      goVersion,
		UnicodeVersion: uver,
		Predicates:     map[string]entry{},
		Tables:         map[string]entry{},
		Mappings:       map[string]mapEntry{},
	}

	// Each predicate and table checksum is FNV-1a over the 4 LE bytes of every
	// rune (in increasing order) for which it is true.
	checkSet := func(pred func(rune) bool) entry {
		h := uint32(fnvOffset)
		n := 0
		for r := 0; r <= maxRune; r++ {
			if pred(rune(r)) {
				h = fnvAdd(h, uint32(r))
				n++
			}
		}
		return entry{Count: n, Checksum: h}
	}
	for _, p := range predicates {
		out.Predicates[p.name] = checkSet(p.fn)
	}
	for _, t := range tables {
		tab := t.tab
		out.Tables[t.name] = checkSet(func(r rune) bool { return unicode.Is(tab, r) })
	}

	// Each mapping checksum is FNV-1a over the 4 LE bytes of f(r) for every
	// rune 0..maxRune.
	mapFns := []struct {
		name string
		fn   func(rune) rune
		ch   int
	}{
		{"ToLower", unicode.ToLower, lowerChanged},
		{"ToUpper", unicode.ToUpper, upperChanged},
		{"ToTitle", unicode.ToTitle, titleChanged},
		{"SimpleFold", unicode.SimpleFold, foldChanged},
	}
	for _, m := range mapFns {
		h := uint32(fnvOffset)
		for r := 0; r <= maxRune; r++ {
			h = fnvAdd(h, uint32(m.fn(rune(r))))
		}
		out.Mappings[m.name] = mapEntry{Changed: m.ch, Checksum: h}
	}

	probeValues := []int64{
		-2147483648, -1000000, -2, -1, 0, 0x7F, 0x80, 0xFF, 0x100, 0x41, 0x61,
		0x130, 0x131, 0x17F, 0x212A, 0x3A3, 0x1E9E, 0xD7FF, 0xD800, 0xDFFF, 0xE000,
		0xFFFD, 0xFFFE, 0x10FFFF, 0x110000, 0x110001, 0x1FFFFF, 0x7FFFFFFF,
	}
	for _, v := range probeValues {
		r := rune(int32(v))
		p := probe{R: v, Predicates: map[string]bool{}, Mappings: map[string]int64{}}
		for _, pr := range predicates {
			p.Predicates[pr.name] = pr.fn(r)
		}
		for _, t := range tables {
			p.Predicates["Is"+t.name] = unicode.Is(t.tab, r)
		}
		p.Mappings["ToLower"] = int64(unicode.ToLower(r))
		p.Mappings["ToUpper"] = int64(unicode.ToUpper(r))
		p.Mappings["ToTitle"] = int64(unicode.ToTitle(r))
		p.Mappings["SimpleFold"] = int64(unicode.SimpleFold(r))
		out.Probes = append(out.Probes, p)
	}

	data, err := json.MarshalIndent(out, "", "  ")
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*checksumsPath, append(data, '\n'), 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %s and %s (%s, unicode %s)", *tablesPath, *checksumsPath, goVersion, uver)
}
